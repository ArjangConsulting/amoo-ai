// swiftlint:disable multiline_arguments
import StudioProtocol

// Emits an XCTestCase driving `XCUIApplication` directly — no amoo companion app involved at run time.
// swiftlint:disable:next type_body_length
public struct XCUITestEmitter: StudioCodeEmitting {
    private let useTestCommons: Bool

    /// Creates an emitter. Shared helpers require TestCommonsXCUI in the receiving UI-test target.
    /// - Parameter useTestCommons: Whether to import and delegate to the shared helper library.
    public init(useTestCommons: Bool = false) {
        self.useTestCommons = useTestCommons
    }

    // SwiftLint measures the generated XCTest helper template as Swift function body lines.
    // swiftlint:disable:next function_body_length
    public func generate(_ test: StudioAuthoredTest) throws -> StudioTestExportResult {
        guard let operations = test.compiledPlan?.toolOperations, operations.isEmpty == false else {
            throw TestCodeGeneratorError.missingCompiledPlan
        }
        let className = "\(TestIdentifierNaming.pascalCase(test.name))Test"
        let methodName = "test\(TestIdentifierNaming.pascalCase(test.name))"
        var localNames = LocalNameAllocator()
        var lookups = [String: String]()
        var statements = try operations.map {
            try Self.statement(
                for: $0, context: test.testContext, localNames: &localNames, lookups: &lookups
            )
        }
        for warning in (test.compiledPlan?.excludedWarnings ?? []).reversed() {
            let message =
                "Uncompiled required action \(warning.actionIndex) (\(warning.toolName)): \(warning.reason)"
            statements.insert(
                "        XCTFail(\(Self.literal(message)))",
                at: min(warning.actionIndex, statements.count)
            )
        }
        let body = Self.collapsingRepeatedWaits(statements.joined(separator: "\n"))
        let contextImports = TestHelperRendering.imports(for: test.testContext)
            .map { "import \($0)" }
            .joined(separator: "\n")
        // The emitter launches unless the context declares that the harness already does. Naming a
        // base class is not that declaration — see `StudioTestContext.harnessLaunchesApp`. The
        // overrides chain to super either way, or a supplied base class's own setUp never runs.
        let baseClass = test.testContext?.baseClass ?? "XCTestCase"
        let appFactory = test.testContext?.appFactory ?? "XCUIApplication()"
        let launchConfiguration = Self.launchConfiguration(for: test)
        let launch =
            test.testContext?.harnessLaunchesApp == true
                ? "" : "\n\(launchConfiguration)        app.launch()"

        let (idiomImport, idiomGuard) = Self.idiomGuard(for: test.testContext)
        // A custom base class may declare its own lifecycle methods without actor isolation, and an
        // override inherits the isolation of the method it overrides, not of this class: a
        // `setUpWithError` override would then touch `app` from a nonisolated context, and wrapping
        // the body in `MainActor.assumeIsolated` is rejected as "sending 'self'". XCTest's async
        // `setUp()` / `tearDown()` are main-actor isolated and run after / before the synchronous
        // pair, so for a custom base the setup and teardown work lives there and the base class's
        // own `setUpWithError` / `tearDownWithError` keep running untouched. A plain `XCTestCase`
        // base overrides the synchronous pair directly, as before.
        let customBase = baseClass != "XCTestCase"
        let setUpBody = "        continueAfterFailure = false\(idiomGuard)\(launch)"
        let lifecycle = customBase
            ? """
            override func setUp() async throws {
                    try await super.setUp()
            \(setUpBody)
                }

                override func tearDown() async throws {
            \(Self.failureAttachments)
                    try await super.tearDown()
                }
            """
            : """
            override func setUpWithError() throws {
                    try super.setUpWithError()
            \(setUpBody)
                }

                override func tearDownWithError() throws {
            \(Self.failureAttachments)
                    try super.tearDownWithError()
                }
            """
        // Only a test that asserts selection carries the wait for it.
        let selectionHelper = body.contains("waitForSelection(") ? Self.selectionHelper : ""

        var source = """
        import XCTest\(idiomImport)\(contextImports.isEmpty ? "" : "\n\(contextImports)")

        /// Generated by amoo from the Studio test "\(test.name)". Edit freely — this file has no
        /// dependency on amoo or the companion apps once generated.
        @MainActor
        final class \(className): \(baseClass) {
            private let defaultTimeout: TimeInterval = 5
            private lazy var app = \(appFactory)

            \(lifecycle)

            private func waitForExistence(
                _ element: XCUIElement,
                named name: String = "Element",
                timeout: TimeInterval? = nil,
                file: StaticString = #filePath,
                line: UInt = #line
            ) {
                XCTAssertTrue(
                    element.waitForExistence(timeout: timeout ?? defaultTimeout),
                    "\\(name) did not exist before the timeout.\\n\\(element.debugDescription)",
                    file: file,
                    line: line
                )
            }

            private func waitForHittability(
                _ element: XCUIElement,
                named name: String = "Element",
                timeout: TimeInterval? = nil,
                file: StaticString = #filePath,
                line: UInt = #line
            ) {
                XCTAssertTrue(
                    element.wait(for: \\.isHittable, toEqual: true, timeout: timeout ?? defaultTimeout),
                    "\\(name) was not visible and hittable before the timeout.\\n\\(element.debugDescription)",
                    file: file,
                    line: line
                )
            }

            private func waitForAbsence(
                _ element: XCUIElement,
                named name: String = "Element",
                timeout: TimeInterval? = nil,
                file: StaticString = #filePath,
                line: UInt = #line
            ) {
                XCTAssertTrue(
                    element.wait(for: \\.exists, toEqual: false, timeout: timeout ?? defaultTimeout),
                    "\\(name) still existed after the timeout.\\n\\(element.debugDescription)",
                    file: file,
                    line: line
                )
            }

            private func replaceText(in element: XCUIElement, with text: String) {
                element.tap()
                if let currentValue = element.value as? String, !currentValue.isEmpty {
                    element.typeText(String(repeating: XCUIKeyboardKey.delete.rawValue, count: currentValue.count))
                }
                if !text.isEmpty {
                    element.typeText(text)
                }
            }

            private func pressBack() {
                let backButton = app.navigationBars.buttons.element(boundBy: 0)
                if backButton.exists, backButton.isHittable {
                    backButton.tap()
                } else {
                    app.swipeRight()
                }
            }

        \(selectionHelper)    func \(methodName)() throws {
        \(body)
            }
        }
        """
        if useTestCommons
            || TestHelperRendering.imports(for: test.testContext).contains("TestCommonsXCUI") {
            if !source.contains("import TestCommonsXCUI") {
                source = "import TestCommonsXCUI\n" + source
            }
            let start = source.range(of: "    private func waitForExistence(")!
            let end = source.range(of: "    private func replaceText(")!
            let wrappers = """
                private func waitForExistence(
                    _ element: XCUIElement, named name: String = "Element", timeout: TimeInterval? = nil,
                    file: StaticString = #filePath, line: UInt = #line
                ) {
                    TestCommonsXCUI.waitForExistence(
                        element, timeout: timeout ?? defaultTimeout,
                        named: name, file: file, line: line
                    )
                }

                private func waitForHittability(
                    _ element: XCUIElement, named name: String = "Element", timeout: TimeInterval? = nil,
                    file: StaticString = #filePath, line: UInt = #line
                ) {
                    TestCommonsXCUI.waitForHittability(
                        element, timeout: timeout ?? defaultTimeout,
                        named: name, file: file, line: line
                    )
                }

                private func waitForAbsence(
                    _ element: XCUIElement, named name: String = "Element", timeout: TimeInterval? = nil,
                    file: StaticString = #filePath, line: UInt = #line
                ) {
                    TestCommonsXCUI.waitForAbsence(
                        element, timeout: timeout ?? defaultTimeout,
                        named: name, file: file, line: line
                    )
                }

            """
            source.replaceSubrange(start.lowerBound ..< end.lowerBound, with: wrappers)
            let attachmentStart = source.range(of: "            let screenshot = XCTAttachment")!
            let attachmentEnd = source.range(of: "            add(hierarchy)")!
            source.replaceSubrange(
                attachmentStart.lowerBound ..< attachmentEnd.upperBound,
                with: "            TestCommonsXCUI.attachDiagnostics(of: app, to: self)"
            )
        }
        source = Self.applyingHarness(to: source, context: test.testContext)
        return StudioTestExportResult(fileName: "\(className).swift", source: source + "\n")
    }

    static let indent = "        "

    // A direct switch keeps the supported Studio-tool-to-XCUITest mapping auditable in one place.
    // swiftlint:disable:next cyclomatic_complexity function_body_length
    static func statement(
        for operation: StudioToolOperation,
        context: StudioTestContext?,
        localNames: inout LocalNameAllocator,
        lookups: inout [String: String]
    ) throws -> String {
        if let helper = try TestHelperRendering.call(for: operation, context: context, literal: literal) {
            return "\(indent)\(helper)"
        }
        guard let tool = StudioTool(rawValue: operation.tool) else {
            throw TestCodeGeneratorError.unsupportedTool(operation.tool)
        }
        if let call = try assertionCall(
            operation, context: context, localNames: &localNames, lookups: &lookups
        ) {
            return call
        }
        // No `default`: adding a StudioTool case must fail to compile here until it is handled.
        switch tool {
        case .tapElement:
            let (_, variable, declaration) = try lookup(
                operation, context: context, localNames: &localNames, lookups: &lookups
            )
            return try """
            \(declaration)
            \(indent)\(waitCall("waitForHittability", variable, operation, context: context))
            \(indent)\(variable).tap()
            """

        case .setText:
            guard let value = operation.arguments["value"] else {
                throw TestCodeGeneratorError.missingArgument(tool: operation.tool, argument: "value")
            }
            let (_, variable, declaration) = try lookup(
                operation, context: context, localNames: &localNames, lookups: &lookups
            )
            return try """
            \(declaration)
            \(indent)\(waitCall("waitForHittability", variable, operation, context: context))
            \(indent)replaceText(in: \(variable), with: \(literal(value)))
            """

        case .typeText:
            guard let text = operation.arguments["text"] else {
                throw TestCodeGeneratorError.missingArgument(tool: operation.tool, argument: "text")
            }
            return "\(indent)app.typeText(\(literal(text)))"

        case .swipeInDirection:
            let gesture = try gesture(for: operation)
            guard operation.arguments["element_id"] != nil || operation.arguments["element_label"] != nil else {
                return "\(indent)app.\(gesture)()"
            }
            // Same lookup as every other element step, so a swipe on an element a previous step
            // already bound reuses that variable and honours the context's selector expressions.
            let (_, variable, declaration) = try lookup(
                operation,
                context: context,
                localNames: &localNames,
                lookups: &lookups,
                idKey: "element_id",
                labelKey: "element_label"
            )
            return try """
            \(declaration)
            \(indent)\(waitCall("waitForHittability", variable, operation, context: context))
            \(indent)\(variable).\(gesture)()
            """

        case .scrollToElement:
            return try scrollToElementStatement(
                for: operation, context: context, localNames: &localNames, lookups: &lookups
            )

        case .scroll:
            // GestureDirection inverts scroll for us — see its documentation for why.
            return try "\(indent)app.\(gesture(for: operation))()"

        case .waitForElement, .assertVisible:
            return try waitStatement(
                for: operation,
                exists: true,
                context: context,
                localNames: &localNames,
                lookups: &lookups
            )

        case .assertNotVisible:
            return try waitStatement(
                for: operation,
                exists: false,
                context: context,
                localNames: &localNames,
                lookups: &lookups
            )

        case .assertEnabled:
            let (_, variable, declaration) = try lookup(
                operation, context: context, localNames: &localNames, lookups: &lookups
            )
            return try """
            \(declaration)
            \(indent)\(waitCall("waitForExistence", variable, operation, context: context))
            \(indent)XCTAssertTrue(\(variable).isEnabled)
            """

        case .assertChecked, .assertStateDescription:
            throw TestCodeGeneratorError.unsupportedAssertion(
                tool: operation.tool, emitter: "XCUITest",
                reason: "XCTest does not expose this Android native property; value/selection are not substitutes."
            )

        case .assertSelected:
            let expected = try SelectedAssertion.expectation(operation)
            let (_, variable, declaration) = try lookup(
                operation, context: context, localNames: &localNames, lookups: &lookups
            )
            let timeout = try timeoutExpression(operation, context: context)
            let selectionWait =
                "waitForSelection(\(variable), expected: \(expected), named: \(literal(variable)), timeout: \(timeout))"
            return try """
            \(declaration)
            \(indent)\(waitCall("waitForExistence", variable, operation, context: context))
            \(indent)\(selectionWait)
            """

        case .assertText:
            guard let expected = operation.arguments["value"] ?? operation.arguments["expected"] else {
                throw TestCodeGeneratorError.missingArgument(tool: operation.tool, argument: "value")
            }
            let (_, variable, declaration) = try lookup(
                operation, context: context, localNames: &localNames, lookups: &lookups
            )
            return try """
            \(declaration)
            \(indent)\(waitCall("waitForExistence", variable, operation, context: context))
            \(indent)XCTAssertEqual(\(variable).label, \(literal(expected)))
            """

        case .assertValue:
            let exact = operation.arguments["value"] ?? operation.arguments["expected"]
            let substring = operation.arguments["contains"]
            guard exact != nil || substring != nil else {
                throw TestCodeGeneratorError.missingArgument(tool: operation.tool, argument: "value")
            }
            let (_, variable, declaration) = try lookup(
                operation, context: context, localNames: &localNames, lookups: &lookups
            )
            let assertion = if let exact {
                "XCTAssertEqual(\(variable).value as? String, \(literal(exact)))"
            } else {
                "XCTAssertTrue(((\(variable).value as? String) ?? \"\").contains(\(literal(substring ?? ""))))"
            }
            return try """
            \(declaration)
            \(indent)\(waitCall("waitForExistence", variable, operation, context: context))
            \(indent)\(assertion)
            """

        case .takeScreenshot:
            let variable = localNames.next("screenshot")
            return """
            \(indent)let \(variable) = XCTAttachment(screenshot: app.screenshot())
            \(indent)\(variable).lifetime = .keepAlways
            \(indent)add(\(variable))
            """

        case .pressBack:
            return "\(indent)pressBack()"

        case .relaunchApplication:
            guard let call = context?.relaunchHelper else {
                throw TestCodeGeneratorError.missingArgument(tool: operation.tool, argument: "relaunchHelper")
            }
            lookups.removeAll()
            return "\(indent)\(call)"
        }
    }

    private static func waitStatement(
        for operation: StudioToolOperation,
        exists: Bool,
        context: StudioTestContext?,
        localNames: inout LocalNameAllocator,
        lookups: inout [String: String]
    ) throws -> String {
        let (_, variable, declaration) = try lookup(
            operation, context: context, localNames: &localNames, lookups: &lookups
        )
        let helper =
            exists
                ? (operation.tool == "assert_visible" ? "waitForHittability" : "waitForExistence")
                : "waitForAbsence"
        // The wait already asserts, and `continueAfterFailure = false` stops the test there, so a
        // trailing XCTAssert would be unreachable. Name the element in the wait instead — that is
        // what makes the failure readable.
        return try """
        \(declaration)
        \(indent)\(waitCall(helper, variable, operation, context: context))
        """
    }

    private static func elementVariableName(
        for operation: StudioToolOperation,
        idKey: String = "id",
        labelKey: String = "label",
        containsTextKey: String = "contains_text"
    ) -> String {
        // `name_hint` is a naming-only key the session compiler attaches — from a `find_elements`
        // observation, or from a role it inferred from the flow (a picker's `…PresetOption`). It
        // never affects the selector, so the id/label the query actually uses stays the contract;
        // it wins over the raw label precisely because it is the compiler's more specific answer.
        TestIdentifierNaming.elementVariableBase(
            id: operation.arguments[idKey],
            label: operation.arguments["name_hint"] ?? operation.arguments[labelKey],
            containsText: operation.arguments[containsTextKey],
            elementType: operation.arguments["element_type"] ?? operation.arguments["type"]
        )
    }

    /// XCUITest's gesture method name for this operation's direction.
    private static func gesture(for operation: StudioToolOperation) throws -> String {
        guard let raw = operation.arguments["direction"] else {
            throw TestCodeGeneratorError.missingArgument(tool: operation.tool, argument: "direction")
        }
        return try gestureMethod(GestureDirection.gestureDirection(for: operation.tool, rawDirection: raw))
    }

    // Named components make this tuple an internal rendering detail, never an API value.
    // swiftlint:disable large_tuple
    static func lookup(
        _ operation: StudioToolOperation,
        context: StudioTestContext?,
        localNames: inout LocalNameAllocator,
        lookups: inout [String: String],
        idKey: String = "id",
        labelKey: String = "label"
    ) throws -> (element: String, variable: String, declaration: String) {
        let element = try query(operation, context: context, idKey: idKey, labelKey: labelKey)
        if let variable = lookups[element] {
            return (element, variable, "")
        }
        let mappedID = operation.arguments[idKey].flatMap { context?.selectorExpressions[$0] }
        let base =
            mappedID.map { TestIdentifierNaming.elementVariableBase(id: $0) }
                ?? elementVariableName(for: operation, idKey: idKey, labelKey: labelKey)
        let variable = localNames.next(base)
        lookups[element] = variable
        return (element, variable, "\(indent)let \(variable) = \(element)")
    }

    // swiftlint:enable large_tuple

    static func literal(_ value: String) -> String {
        var escaped =
            value
                .replacingOccurrences(of: "\\", with: "\\\\")
                .replacingOccurrences(of: "\"", with: "\\\"")
                .replacingOccurrences(of: "\n", with: "\\n")
                .replacingOccurrences(of: "\r", with: "\\r")
                .replacingOccurrences(of: "\t", with: "\\t")
        escaped = String(
            escaped.unicodeScalars.map { scalar -> String in
                guard scalar.value < 0x20 else { return String(scalar) }
                return "\\u{\(String(scalar.value, radix: 16))}"
            }.joined()
        )
        return "\"\(escaped)\""
    }
}

